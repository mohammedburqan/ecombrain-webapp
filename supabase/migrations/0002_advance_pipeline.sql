-- ---------------------------------------------------------------------------
-- Storage bucket for brand file uploads (private, 50 MB max)
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('brand-files', 'brand-files', false, 52428800)
on conflict (id) do nothing;

-- Storage RLS: bucket is private; all reads/writes go through signed URLs
-- generated by the service-role client on the server — no direct client access.
-- We add a permissive insert policy so the service role (bypasses RLS) can
-- write, and a select policy so signed-URL generation works.
drop policy if exists "brand_files_insert" on storage.objects;
create policy "brand_files_insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'brand-files');

drop policy if exists "brand_files_select" on storage.objects;
create policy "brand_files_select" on storage.objects
  for select to authenticated
  using (bucket_id = 'brand-files');

