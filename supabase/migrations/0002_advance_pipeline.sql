-- ---------------------------------------------------------------------------
-- advance_pipeline: approve a step and unlock the next one(s).
-- Called by the server-side upload route with the service-role client,
-- so it runs in a SECURITY DEFINER context to write progress rows that
-- students cannot write directly.
--
-- Unlock map (step_id == sort_order in this schema):
--   1 → 2 → 3 → 4 → 5 → 6 → 7 → 8
--   8 → 9, 11, 14   (three parallel unlocks)
--   9 → 10
--   10 + 11 → 12    (AND gate)
--   12 → 13, 15
-- ---------------------------------------------------------------------------
create or replace function public.advance_pipeline(
  p_brand_id uuid,
  p_step_id  int
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_is_repeatable  boolean;
  v_current_status text;
  v_other_approved boolean;
  v_unlock_ids     int[] := '{}';
begin
  -- Verify the caller can see this brand (owner or admin).
  if not exists (
    select 1 from public.brands
    where id = p_brand_id
      and (owner_id = auth.uid() or public.is_ecomskool_admin())
  ) then
    return jsonb_build_object('ok', false, 'error', 'brand_not_found');
  end if;

  -- Fetch step metadata.
  select is_repeatable into v_is_repeatable
  from public.pipeline_steps where id = p_step_id;

  if not found then
    return jsonb_build_object('ok', false, 'error', 'step_not_found');
  end if;

  -- Fetch current progress status.
  select status into v_current_status
  from public.brand_step_progress
  where brand_id = p_brand_id and step_id = p_step_id;

  -- Reject locked steps.
  if v_current_status = 'locked' then
    return jsonb_build_object('ok', false, 'error', 'step_locked');
  end if;

  -- For already-approved non-repeatable steps: the file was already stored
  -- (caller creates step_files row first), but we skip re-gating.
  if v_current_status = 'approved' and not v_is_repeatable then
    return jsonb_build_object('ok', true, 'already_approved', true);
  end if;

  -- Approve this step.
  update public.brand_step_progress
  set status = 'approved', completed_at = now()
  where brand_id = p_brand_id and step_id = p_step_id;

  -- Determine which steps to unlock (using step_id which equals sort_order).
  case p_step_id
    when 1  then v_unlock_ids := array[2];
    when 2  then v_unlock_ids := array[3];
    when 3  then v_unlock_ids := array[4];
    when 4  then v_unlock_ids := array[5];
    when 5  then v_unlock_ids := array[6];
    when 6  then v_unlock_ids := array[7];
    when 7  then v_unlock_ids := array[8];
    when 8  then v_unlock_ids := array[9, 11, 14];  -- parallel launch
    when 9  then v_unlock_ids := array[10];
    when 10 then
      -- AND gate: unlock step 12 only if step 11 is also approved.
      select (status = 'approved') into v_other_approved
      from public.brand_step_progress where brand_id = p_brand_id and step_id = 11;
      if coalesce(v_other_approved, false) then
        v_unlock_ids := array[12];
      end if;
    when 11 then
      -- AND gate: unlock step 12 only if step 10 is also approved.
      select (status = 'approved') into v_other_approved
      from public.brand_step_progress where brand_id = p_brand_id and step_id = 10;
      if coalesce(v_other_approved, false) then
        v_unlock_ids := array[12];
      end if;
    when 12 then v_unlock_ids := array[13, 15];
    else v_unlock_ids := '{}';
  end case;

  -- Unlock the next steps (only those currently locked).
  if array_length(v_unlock_ids, 1) > 0 then
    update public.brand_step_progress
    set status = 'unlocked', unlocked_at = now()
    where brand_id = p_brand_id
      and step_id = any(v_unlock_ids)
      and status = 'locked';
  end if;

  return jsonb_build_object('ok', true, 'unlocked', v_unlock_ids);
end;
$$;
